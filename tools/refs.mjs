#!/usr/bin/env node
// Builds licensed reference data for the lab. Output is gitignored: it exists
// only on a machine that holds the licences.
//
//   node tools/refs.mjs            → lab/refs.js          (the 14-subject character grid)
//   node tools/refs.mjs <concept>  → lab/refs/current.js  (the icon on the drawing board, for lab/icon.html)
//   node tools/refs.mjs <concept> --out lab/refs/batch/<concept>.js
//                                  → anywhere else; used for a batch of boards, which
//                                    lab/icon.html reads with ?icon=<concept>
//
// Sources
//   Polaris  research/references/polaris/  (fetched from the archive on demand; 20 grid, fills)
//   Nucleo   the Nucleo app's local library (UI family, 18 + 12 grids, outline)
//   Lucide   research/references/lucide/    (fetched from lucide-static on demand; ISC)
//   Central  research/references/central/<concept>.json (captured from centralicons.com)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';

const NUCLEO = join(homedir(), 'Library/Application Support/Nucleo/icons');
const inner = (svg) => svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
  .replace(/<g class="nc-icon-wrapper">|<\/g>/g, '').replace(/stroke="(#000|black)"/g, 'stroke="currentColor"')
  .replace(/fill="(#000|black)"/g, 'fill="currentColor"').trim();

async function cached(dir, file, url) {
  mkdirSync(dir, { recursive: true });
  const f = join(dir, file);
  if (!existsSync(f)) {
    const r = await fetch(url);
    if (!r.ok) return null;
    writeFileSync(f, await r.text());
  }
  return readFileSync(f, 'utf8');
}

const argv = process.argv.slice(2);
const outAt = argv.indexOf('--out');
const OUT = outAt < 0 ? 'lab/refs/current.js' : argv[outAt + 1];
const concept = argv.filter((a, i) => !a.startsWith('--') && !(outAt >= 0 && i === outAt + 1))[0];
if (concept) await one(concept); else character();

async function one(c) {
  const audit = JSON.parse(readFileSync('research/audit.json', 'utf8'));
  const row = [...audit.ranked, ...audit.excluded].find((r) => r.concept === c);
  const names = row?.names ?? { polaris: [], nucleo: [], lucide: [] };
  const out = { concept: c, rank: row?.rank ?? null, polaris: [], nucleo: [], lucide: [], central: {} };

  for (const n of names.polaris) {
    const pascal = n.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join('');
    for (const v of [pascal, `${pascal}Filled`]) {
      const svg = await cached('research/references/polaris', `${v}.svg`,
        `https://raw.githubusercontent.com/Shopify/polaris-react-archive/main/polaris-icons/icons/${v}Icon.svg`);
      if (svg?.includes('<svg')) out.polaris.push({ name: v, svg: inner(svg) });
    }
  }

  const db = new DatabaseSync(join(NUCLEO, 'data.sqlite3'), { readOnly: true });
  const wanted = [...new Set([c, ...names.nucleo])];
  const q = db.prepare(`SELECT id, set_id, name, grid FROM icons
    WHERE name = ? AND set_id BETWEEN 10 AND 47 AND klass = 'outline' AND grid IN (18, 12) ORDER BY grid DESC, set_id`);
  const seen = new Set();
  for (const n of wanted) {
    for (const r of q.all(n)) {
      const key = `${r.name}@${r.grid}`;
      const f = join(NUCLEO, 'sets', String(r.set_id), `${r.id}.svg`);
      if (seen.has(key) || !existsSync(f)) continue;
      seen.add(key);
      out.nucleo.push({ name: r.name, grid: r.grid, svg: inner(readFileSync(f, 'utf8')) });
    }
  }

  for (const n of names.lucide) {
    const svg = await cached('research/references/lucide', `${n}.svg`, `https://cdn.jsdelivr.net/npm/lucide-static@latest/icons/${n}.svg`);
    if (svg) out.lucide.push({ name: n, svg: inner(svg) });
  }

  const cf = `research/references/central/${c}.json`;
  if (existsSync(cf)) out.central = JSON.parse(readFileSync(cf, 'utf8'));

  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, `// generated by tools/refs.mjs — licensed, gitignored\nexport default ${JSON.stringify(out)};\n`);
  console.log(`${c}: polaris ${out.polaris.length} · nucleo ${out.nucleo.length} · lucide ${out.lucide.length} · central ${Object.values(out.central).reduce((a, v) => a + Object.keys(v).length, 0)} → ${OUT}`);
}

function character() {
  // subject → [Polaris file, Nucleo icon id]
  const SUBJECTS = {
    calendar: ['Calendar', 2328], user: ['Person', 2344], trash: ['Delete', 2474],
    folder: ['Folder', 2409], bell: ['Notification', 2326], home: ['Home', 2331],
    lock: ['Lock', 2309], file: ['File', 2406], heart: ['Heart', 2278],
    settings: ['Settings', 2459], clock: ['Clock', 6400], 'check-circle': ['CheckCircle', 9835],
    'chevron-right': ['ChevronRight', 2269], 'credit-card': ['CreditCard', 2435],
  };
  const nucleoSet = { 6400: 43, 9835: 45 };            // ids that live outside set 10
  const central = JSON.parse(readFileSync('research/references/central.json', 'utf8'));
  const sets = { polaris: {}, nucleo: {}, centralS15: {}, centralR2: {}, centralR3: {} };
  for (const [s, [p, n]] of Object.entries(SUBJECTS)) {
    const pf = `research/references/polaris/${p}.svg`;
    if (existsSync(pf)) sets.polaris[s] = inner(readFileSync(pf, 'utf8'));
    const nf = join(NUCLEO, 'sets', String(nucleoSet[n] ?? 10), `${n}.svg`);
    if (existsSync(nf)) sets.nucleo[s] = inner(readFileSync(nf, 'utf8'));
    sets.centralS15[s] = central['stroke1.5-radius2'][s];
    sets.centralR2[s] = central['stroke2-radius2'][s];
    sets.centralR3[s] = central['stroke2-radius3'][s];
  }
  writeFileSync('lab/refs.js', `// generated by tools/refs.mjs — licensed, gitignored\nexport const REFS = ${JSON.stringify(sets)};\n`);
  console.log(Object.entries(sets).map(([k, v]) => `${k} ${Object.keys(v).length}`).join(' · '), '→ lab/refs.js');
}
